import { ref } from 'vue';

/**
 * Картинка, открытая на весь экран, — одна на всё приложение.
 *
 * Снимки в кэше 400–700 точек шириной, а в строке таблицы нарисованы в 56 и в
 * карточке — в три сотни: разглядеть узор на детали по ним нельзя. Оверлей
 * показывает то же изображение во всю доступную высоту, и ничего больше: для
 * этого хватает одного состояния на страницу, а не окна у каждой картинки.
 *
 * Описание хранится, а не готовый адрес: картинку рисуют ItemImage и
 * AssemblyImage, каждая по своим правилам — кэш, источник, заглушка, — и
 * повторять их выбор здесь значило бы завести второе место, где он делается.
 */
export const shown = ref(null);

/**
 * @param {{kind: 'item'|'assembly', title: string, subtitle?: string|null}} picture
 */
export function zoom(picture) {
    shown.value = picture;
}

export function closeZoom() {
    shown.value = null;
}
