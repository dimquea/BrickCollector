/**
 * Путь, под которым приложение видно браузеру.
 *
 * В обычной установке — пустая строка. Под Home Assistant Ingress — префикс
 * вида /api/hassio_ingress/<токен>, который сервер положил в window.__base.
 *
 * Через этот помощник проходит всё, что уходит в сеть: ссылки, переходы
 * роутера, сохранения через axios, адреса картинок.
 */
export const base = typeof window === 'undefined' ? '' : (window.__base ?? '');

/**
 * Дополняет путь префиксом — но только если его там ещё нет.
 *
 * Идемпотентность здесь не украшение: часть адресов приходит с сервера уже с
 * префиксом (ссылки постранички, например), и второе применение превращало их
 * в /api/.../api/.../sets.
 */
export function url(path) {
    if (base === '' || path.startsWith(`${base}/`) || path === base) {
        return path;
    }

    return base + path;
}
