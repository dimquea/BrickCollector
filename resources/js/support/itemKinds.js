/**
 * Виды предметов, из которых состоит набор.
 *
 * Порядок — от крупного к мелкому: поднабор, фигурка, деталь, и следом то, что
 * лежит в коробке, но не строится, — сопутствующее, книга, каталог. Последние
 * три долго не показывались вовсе: состав рисовался по списку «S, M, P», и
 * коробка-органайзер, записанная в наборе отдельной позицией, пропадала.
 *
 * Названия берутся из переводов, а не из справочника: там они английские, и
 * «Gear» рядом с «Деталями» читалось бы как чужое слово.
 */
export const KIND_ORDER = ['S', 'M', 'P', 'G', 'B', 'C'];

const LABELS = {
    S: 'item.subsets',
    M: 'item.minifigures',
    P: 'item.parts',
    G: 'item.gear',
    B: 'item.books',
    C: 'item.catalogs',
};

/** Ключ перевода для вида предмета; для незнакомого — сам код типа. */
export function kindLabel(code) {
    return LABELS[code] ?? code;
}
